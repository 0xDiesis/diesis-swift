#!/usr/bin/env python3
"""Regenerate the Swift bindings, addresses, chains, and contract table.

Usage:
    python3 scripts/generate.py          # regenerate everything in place
    python3 scripts/generate.py --check  # fail if anything is out of date

Inputs:
    DIESIS_CONTRACTS_DIR  contracts checkout with compiled artifacts in out/
                          (default: ../../diesis-core/diesis/contracts)
    ABI_TYPEGEN           abi-typegen binary, 0.8.0 or later
                          (default: <contracts>/node_modules/.bin/abi-typegen)
    ../diesis-js/canonical.json  source of the vendored canonical.json

Uses only the Python standard library.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "Sources" / "Diesis"
GENERATED_DIR = SOURCES / "Generated"
CANONICAL = ROOT / "canonical.json"
SDK_CANONICAL = ROOT.parent / "diesis-js" / "canonical.json"

